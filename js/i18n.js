/**
 * Look up a string, filling {placeholders}. Falls back to the key itself.
 * When vars.n is exactly 1 and a "key.one" string exists, that one is used ("1 trade", not "1 trades").
 */
export function t(key, vars) {
  let str = (vars && String(vars.n) === '1' && en[key + '.one']) || (en[key] ?? key);
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.split('{' + k + '}').join(String(v));
  return str;
}
